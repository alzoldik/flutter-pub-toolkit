import { promises as fs } from 'fs';
import * as path from 'path';

const RESERVED = new Set(['abstract', 'as', 'assert', 'async', 'await', 'break', 'case', 'catch', 'class', 'const',
  'continue', 'default', 'do', 'else', 'enum', 'export', 'extends', 'external', 'factory', 'false', 'final', 'finally',
  'for', 'get', 'if', 'implements', 'import', 'in', 'is', 'late', 'library', 'new', 'null', 'operator', 'part',
  'required', 'rethrow', 'return', 'set', 'static', 'super', 'switch', 'this', 'throw', 'true', 'try', 'var',
  'void', 'while', 'with', 'yield', 'values', 'hashCode', 'runtimeType', 'toString']);

/** Reads `flutter: assets:` entries (string form and `- path:` form). */
export function parseAssetEntries(pubspec: string): string[] {
  const lines = pubspec.split(/\r?\n/);
  const out: string[] = [];
  let inFlutter = false;
  let assetsIndent: number | undefined;
  for (const line of lines) {
    if (!line.trim() || line.trim().startsWith('#')) { continue; }
    const indent = line.length - line.trimStart().length;
    if (indent === 0) {
      inFlutter = /^flutter\s*:/.test(line);
      assetsIndent = undefined;
      continue;
    }
    if (!inFlutter) { continue; }
    if (assetsIndent === undefined) {
      if (/^\s+assets\s*:\s*$/.test(line)) { assetsIndent = indent; }
      continue;
    }
    if (indent <= assetsIndent) { assetsIndent = /^\s+assets\s*:\s*$/.test(line) ? indent : undefined; continue; }
    const m = /^\s*-\s*(?:path\s*:\s*)?['"]?([^'"#]+?)['"]?\s*(#.*)?$/.exec(line);
    if (m) { out.push(m[1].trim()); }
  }
  return out;
}

function identifier(assetPath: string, used: Set<string>): string {
  const noRoot = assetPath.replace(/^assets\//, '');
  const ext = path.extname(noRoot);
  const base = noRoot.slice(0, noRoot.length - ext.length) || noRoot;
  const make = (s: string) => {
    const parts = s.split(/[^a-zA-Z0-9]+/).filter(Boolean);
    let id = parts.map((p, i) => (i === 0 ? p.charAt(0).toLowerCase() + p.slice(1) : p.charAt(0).toUpperCase() + p.slice(1))).join('');
    if (!id) { id = 'asset'; }
    if (/^\d/.test(id)) { id = 'a' + id; }
    if (RESERVED.has(id)) { id += 'Asset'; }
    return id;
  };
  let id = make(base);
  if (used.has(id)) { id = make(base + '_' + ext.replace('.', '')); }
  let n = 2;
  const root = id;
  while (used.has(id)) { id = `${root}${n++}`; }
  used.add(id);
  return id;
}

export interface GenerateResult { file: string; count: number }

export async function generateAssetsFile(projectDir: string, outputRel: string, className: string): Promise<GenerateResult> {
  const pubspec = await fs.readFile(path.join(projectDir, 'pubspec.yaml'), 'utf8');
  const entries = parseAssetEntries(pubspec);
  const files = new Set<string>();
  for (const entry of entries) {
    const abs = path.join(projectDir, entry);
    try {
      const stat = await fs.stat(abs);
      if (stat.isDirectory()) {
        // Flutter includes only the files directly inside a listed directory.
        for (const name of (await fs.readdir(abs)).sort()) {
          if (name.startsWith('.')) { continue; }
          const child = path.join(abs, name);
          if ((await fs.stat(child)).isFile()) {
            files.add(path.posix.join(entry.replace(/\/$/, ''), name));
          }
        }
      } else {
        files.add(entry);
      }
    } catch { /* missing asset path: skip */ }
  }

  const used = new Set<string>();
  const byFolder = new Map<string, string[]>();
  for (const f of [...files].sort()) {
    const dir = path.posix.dirname(f);
    const line = `  static const String ${identifier(f, used)} = '${f.replace(/'/g, "\\'")}';`;
    byFolder.set(dir, [...(byFolder.get(dir) ?? []), line]);
  }
  const body = [...byFolder.entries()].map(([dir, lines]) => `  // ${dir}/\n${lines.join('\n')}`).join('\n\n');
  const all = [...files].map((f) => `    '${f.replace(/'/g, "\\'")}',`).join('\n');
  const content = `// GENERATED CODE - DO NOT MODIFY BY HAND
// Generated by Flutter Pub Toolkit from pubspec.yaml assets.
// ignore_for_file: constant_identifier_names, lines_longer_than_80_chars

class ${className} {
  ${className}._();

${body}

  static const List<String> values = [
${all}
  ];
}
`;
  const out = path.join(projectDir, outputRel);
  await fs.mkdir(path.dirname(out), { recursive: true });
  await fs.writeFile(out, content, 'utf8');
  return { file: out, count: files.size };
}
